for i in range(3):
    print("Hello World!")

'''
Range basically generates a sequence of numbers. In this case, range(3) generates the numbers 0, 1, and 2. 
The for loop iterates over this sequence, and for each number (0, 1, and 2), it executes the block of code indented under it, which prints "Hello World!" three times.
 The variable i takes on the value of each number in the sequence during each iteration of the loop, but in this case, it is not used inside the loop body.
'''
